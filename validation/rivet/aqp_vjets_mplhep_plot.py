#!/usr/bin/env python3
"""Apply mplhep ATLAS visual styling to original Rivet-generated plot scripts.

Rivet/YODA's autogenerated scripts remain authoritative for all numerical
content: binning, values, normalization, colors, legend text, axes, ranges,
error bars (including ratio-panel errors), and curve drawing instructions.
This wrapper changes only stylesheet, text/figure layout and in-axes
ATLAS labeling. No original source, YODA, or __data.py file is modified.

Input is trusted Rivet-generated code: as in rivet-mkhtml, each script
executes its accompanying __data.py file.
"""
import argparse
import ast
import csv
import html
import re
from pathlib import Path

ANALYSES = {"Zee": ("MC_ZJETS", "MC_ZINC"),
            "Wenu": ("MC_WJETS", "MC_WINC")}
FRESH_ANALYSES = {
    "Zee": (*ANALYSES["Zee"], "MC_KTSPLITTINGS", "MC_ZKTSPLITTINGS",
            "MC_WEIGHTS", "MC_XS", "ATLAS_2017_I1514251",
            "CMS_2018_I1667854", "ATLAS_2022_I2077570"),
    "Wenu": (*ANALYSES["Wenu"], "MC_KTSPLITTINGS", "MC_WEIGHTS",
             "MC_XS", "ATLAS_2024_I2765017"),
}
# Known inconsistent or misleading finalized observables: keep native
# exports available, but do not include them in the validated gallery.
DIAGNOSTICS = {("MC_XS", "XS"), ("MC_WEIGHTS", "xsfraction_neg")}


def analysis_directory(source, process, analysis, fresh=False):
    if not fresh:
        return source / process / "01_four_way_common_MC_shapes" / analysis
    base = source / process
    matches = [p for p in base.iterdir()
               if p.is_dir() and p.name.split(":")[0] == analysis] if base.is_dir() else []
    if len(matches) != 1:
        # Rivet can encode the analysis options in the directory name.
        matches = [p for p in base.iterdir()
                   if p.is_dir() and p.name.startswith(analysis + "_")] if base.is_dir() else []
    if len(matches) != 1:
        raise ValueError(f"Expected one fresh analysis directory: {base}/{analysis}; found {matches}")
    return matches[0]


STYLE_LINE = "plt.style.use(os.path.join(plotDir, '../default.mplstyle'))"
FONT_LINE = "plt.rc('font', family='DejaVu Sans')"
LABEL_ANCHOR = "fig.align_ylabels((ax, ratio0_ax))"
# Presentation-only: thicken the stepped HISTOGRAM outlines; keep the original
# .errorbar() call, its yerrs/xerrs and error-bar line widths untouched.
HIST_LINE_WIDTH = 1.8
HIST_UPPER_LINE = ("linewidth=styles[label]['linewidth'],\n"
                   "                       drawstyle=styles[label]['drawstyle']")
HIST_RATIO_LINE = ("linewidth=styles[label]['linewidth'],\n"
                   "                       linestyle=styles[label]['ratio0_linestyle']")


# Typography only: all line colors/markers/error bar settings come from
# the original Rivet plot script, never from a replacement palette.
ATLAS_STYLE = """plt.style.use(hep.style.ATLAS)
plt.rcParams.update({
    'figure.figsize': (9.2, 7.8),
    'font.size': 12.5,
    'axes.labelsize': 14,
    'axes.titlesize': 15,
    'xtick.labelsize': 11,
    'ytick.labelsize': 11,
    'legend.fontsize': 10.5,
    'legend.title_fontsize': 10.5,
    'savefig.bbox': 'tight',
    'savefig.pad_inches': 0.15,
})"""


FOLDING_LABELS = {"S111": "MC@NLO, folding 111",
                  "D111": "MC@NLO-Δ, folding 111",
                  "D221": "MC@NLO-Δ, folding 221",
                  "D441": "MC@NLO-Δ, folding 441"}


def restyle_script(original, folding_labels=False):
    """Retain every Rivet physics plotting statement, replacing only styling."""
    for token in (STYLE_LINE, FONT_LINE, LABEL_ANCHOR):
        if original.count(token) != 1:
            raise ValueError("Expected exactly one Rivet plotting anchor: " + token)
    if "__data.py" not in original or "ratio0_yerrs" not in original:
        raise ValueError("Not a standard Rivet four-way plotting script")
    if "bbox_to_anchor=" not in original or "ax.add_artist(ax.legend(" not in original:
        raise ValueError("Expected Rivet in-axes legend not found")

    restyled = original.replace("import matplotlib.pyplot as plt",
        "import matplotlib.pyplot as plt\nimport mplhep as hep", 1)
    restyled = restyled.replace(STYLE_LINE, ATLAS_STYLE, 1)
    restyled = restyled.replace(
        FONT_LINE, "# Font is provided by mplhep ATLAS style.", 1)

    # Only the two step-curve ax.plot()/ratio0_ax.plot() linewidths change.
    # Rivet's error bars retain their native linewidth and uncertainty arrays.
    for anchor in (HIST_UPPER_LINE, HIST_RATIO_LINE):
        if restyled.count(anchor) != 1:
            raise ValueError("Expected a single Rivet histogram-line anchor: " + anchor)
        restyled = restyled.replace(
            anchor, anchor.replace("linewidth=styles[label]['linewidth']",
                                   f"linewidth={HIST_LINE_WIDTH} * styles[label]['linewidth']"),
            1)

    # Original legend stays inside the axes and is *not* moved/relabelled.
    # The ATLAS label gets a different corner for plots with upper-left legend.
    if re.search(r"loc='upper left'\s*,", original):
        label = ("ax.text(0.97, 0.96, r'$\\bf{ATLAS}$ Simulation Internal', "
                 "ha='right', va='top', transform=ax.transAxes, fontsize=11)")
    else:
        label = "hep.atlas.label('Internal', data=False, ax=ax, loc=1, fontsize=11)"
    layout = ("ratio0_ax.xaxis.label.set_horizontalalignment('right')\n"
              "ratio0_ax.xaxis.set_label_coords(0.96, -0.15)\n"
              "fig.subplots_adjust(right=0.94, bottom=0.16)")
    restyled = restyled.replace(
        LABEL_ANCHOR, LABEL_ANCHOR + "\n" + layout + "\n" + label, 1)
    if folding_labels:
        # Edit rendered legend texts only, not curve keys, axes or arrays.
        relabel = ("from matplotlib.legend import Legend\n"
                   f"_aqp_labels = {FOLDING_LABELS!r}\n"
                   "for _aqp_legend in ax.findobj(match=Legend):\n"
                   "    for _aqp_text in _aqp_legend.get_texts():\n"
                   "        _aqp_text.set_text(_aqp_labels.get(_aqp_text.get_text(), _aqp_text.get_text()))")
        restyled = restyled.replace(LABEL_ANCHOR, relabel + "\n" + LABEL_ANCHOR, 1)
    return restyled


def inspect_script(source):
    """Extract plot provenance without executing the Rivet-generated script."""
    tree = ast.parse(source)
    out = {}
    names = {"ax_xLabel", "ax_yLabel", "ax_xScale", "ax_yScale",
             "ax_title", "xLims", "yLims"}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            target = node.targets[0]
            if isinstance(target, ast.Name) and target.id in names:
                try:
                    out[target.id] = ast.literal_eval(node.value)
                except (ValueError, TypeError, SyntaxError, NameError):
                    pass
    return out


def render_one(script, dest, check_only=False, folding_labels=False):
    original = script.read_text(encoding="utf-8")
    metadata = inspect_script(original)
    restyled = restyle_script(original, folding_labels=folding_labels)
    program = compile(restyled, str(script), "exec")
    if check_only:
        return metadata

    dest.mkdir(parents=True, exist_ok=True)
    # __file__ points to *original* autogenerated script so the numerical
    # __data.py file remains the one emitted by Rivet. Only the output path
    # is redirected. Neither original file is touched.
    env = {"__file__": str(script.resolve()),
           "__name__": "__main__",
           "YODA_USER_PLOT_PATH": str(dest.resolve())}
    exec(program, env)
    for suffix in ("pdf", "png"):
        if not (dest / (script.stem + "." + suffix)).is_file():
            raise RuntimeError("Missing " + suffix + " output from " + str(script))
    return metadata


def run(source, output, check_only=False, folding_labels=False, fresh=False):
    import matplotlib
    matplotlib.use("Agg")
    if not check_only:
        import mplhep
        _ = mplhep.style.ATLAS

    records, gallery, failures = [], [], []
    for process, analyses in (FRESH_ANALYSES if fresh else ANALYSES).items():
        for analysis in analyses:
            try:
                directory = analysis_directory(source, process, analysis, fresh)
            except ValueError as exc:
                failures.append(str(exc))
                continue
            originals = sorted(x for x in directory.glob("*.py")
                               if not x.name.endswith("__data.py"))
            if not originals:
                failures.append("No Rivet plotting scripts in " + str(directory))
            plots = []
            for script in originals:
                try:
                    if not script.with_name(script.stem + "__data.py").is_file():
                        raise ValueError("Original Rivet numerical export missing")
                    if fresh and (analysis, script.stem) in DIAGNOSTICS:
                        print(f"SKIP_DIAGNOSTIC={script}")
                        continue
                    meta = render_one(script, output / process / analysis,
                                      check_only=check_only, folding_labels=folding_labels)
                    records.append([
                        process, analysis, script.stem,
                        meta.get("ax_xLabel", ""), meta.get("ax_yLabel", ""),
                        meta.get("ax_xScale", ""), meta.get("ax_yScale", ""),
                        str(meta.get("xLims", "")), str(meta.get("yLims", ""))])
                    plots.append(script.stem)
                except Exception as exc:
                    failures.append(str(script) + ": " + type(exc).__name__
                                    + ": " + str(exc))
            gallery.append((process, analysis, plots))
    if not check_only:
        output.mkdir(parents=True, exist_ok=True)
        with (output / "manifest.csv").open("w", newline="") as stream:
            writer = csv.writer(stream)
            writer.writerow(["process", "analysis", "histogram", "rivet_x_label",
                             "rivet_y_label", "rivet_x_scale", "rivet_y_scale",
                             "rivet_x_limits", "rivet_y_limits"])
            writer.writerows(records)
        page = ['<!DOCTYPE html><html><head><meta charset="utf-8">',
                '<title>AQP - Rivet histograms with mplhep ATLAS style</title>',
                '</head><body><h1>AQP V+jets - original Rivet curves, ATLAS style</h1>']
        for process, analysis, plots in gallery:
            page.append(f'<h2>{html.escape(process)} / {html.escape(analysis)} '
                        f'({len(plots)} plots)</h2>')
            for name in plots:
                rel = f'{process}/{analysis}/{name}'
                page.append(f'<details><summary>{html.escape(name)}</summary>'
                            f'<a href="{html.escape(rel)}.pdf">PDF</a><br>'
                            f'<img loading="lazy" style="max-width:100%" '
                            f'src="{html.escape(rel)}.png"></details>')
        if failures:
            page.append('<pre>' + html.escape("\n".join(failures)) + '</pre>')
        page.append('</body></html>')
        (output / "index.html").write_text("\n".join(page))
    print(f"PLOTS={len(records)} ERROR_COUNT={len(failures)} OUTPUT={output}")
    for failure in failures:
        print("ERROR:", failure)
    return int(bool(failures))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check-only", action="store_true")
    parser.add_argument("--folding-labels", action="store_true",
                        help="Expand S111/D111/D221/D441 legend texts only")
    parser.add_argument("--fresh", action="store_true", help="Read fresh Rivet plots/PROCESS/ANALYSIS and render all routines")
    args = parser.parse_args()
    raise SystemExit(run(args.source, args.output, args.check_only, args.folding_labels, args.fresh))


if __name__ == "__main__":
    main()
